import 'dart:html' as html;
import 'dart:js_util' as js;
import 'dart:typed_data';

Future<bool> shareSettlementPdf(Uint8List bytes, String filename) async {
  final navigator = html.window.navigator;
  if (!js.hasProperty(navigator, 'share') ||
      !js.hasProperty(navigator, 'canShare')) return false;
  final file = html.File([bytes], filename, {'type': 'application/pdf'});
  final data = js.jsify({
    'files': [file],
    'title': 'Move-out settlement invoice'
  });
  if (js.callMethod<bool>(navigator, 'canShare', [data]) != true) return false;
  // Called directly from the share button with already-generated bytes to keep
  // the browser's user activation. Never generate the PDF before this call.
  try {
    await js.promiseToFuture(js.callMethod(navigator, 'share', [data]));
    return true;
  } catch (error) {
    if (js.hasProperty(error, 'name') &&
        js.getProperty(error, 'name') == 'AbortError') return true;
    return false;
  }
}
