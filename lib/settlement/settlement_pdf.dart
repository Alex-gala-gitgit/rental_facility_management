import 'package:flutter/services.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import '../branding/homeops_brand.dart';
import 'settlement_model.dart';

Future<Uint8List> buildSettlementPdf(MoveOutSettlement settlement) async {
  final data = await rootBundle.load('assets/fonts/Manrope-PdfRegular.ttf');
  final font = pw.Font.ttf(data);
  final boldFont =
      pw.Font.ttf(await rootBundle.load('assets/fonts/Manrope-PdfBold.ttf'));
  final hasNonLatin = RegExp(r'[^\x00-\xFF]').hasMatch(
      '${settlement.tenantName}${settlement.propertyName}${settlement.unitName}${settlement.otherDescription}${settlement.meter?.name ?? ''}${settlement.payslip?.name ?? ''}');
  final fallback = hasNonLatin
      ? [
          pw.Font.ttf(
              await rootBundle.load('assets/fonts/NotoSansSC-Variable.ttf'))
        ]
      : <pw.Font>[];
  final doc = pw.Document(
      theme: pw.ThemeData.withFont(
          base: font,
          bold: boldFont,
          italic: font,
          boldItalic: boldFont,
          fontFallback: fallback));
  final blue = PdfColor.fromHex('#17233C');
  final muted = PdfColor.fromHex('#62708A');
  final line = PdfColor.fromHex('#CCD6E5');
  final green = PdfColor.fromHex('#E8F7F1');
  final refundColor = PdfColor.fromHex('#167457');
  pw.Widget brandHeader() => pw.Row(children: [
        pw.SvgImage(svg: homeOps360IconSvg, width: 28, height: 28),
        pw.SizedBox(width: 8),
        pw.Text('HomeOps360',
            style: pw.TextStyle(
                fontSize: 14,
                color: PdfColor.fromHex('#0E1B33'),
                fontWeight: pw.FontWeight.bold)),
        pw.Spacer(),
        pw.Text('Digital bill generated by HomeOps360',
            style: pw.TextStyle(fontSize: 8, color: muted)),
      ]);
  pw.Widget row(String label, String amount, {bool bold = false}) => pw.Padding(
        padding: const pw.EdgeInsets.symmetric(vertical: 6),
        child:
            pw.Row(crossAxisAlignment: pw.CrossAxisAlignment.start, children: [
          pw.Expanded(
              child: pw.Text(label,
                  style: pw.TextStyle(
                      fontSize: 11,
                      color: blue,
                      fontWeight:
                          bold ? pw.FontWeight.bold : pw.FontWeight.normal))),
          pw.SizedBox(width: 16),
          pw.Text(amount,
              style: pw.TextStyle(
                  fontSize: 11,
                  color: blue,
                  fontWeight:
                      bold ? pw.FontWeight.bold : pw.FontWeight.normal)),
        ]),
      );
  doc.addPage(pw.MultiPage(
    pageFormat: PdfPageFormat.a4,
    margin: const pw.EdgeInsets.fromLTRB(50, 24, 50, 40),
    footer: (context) => pw.Text(
        'HomeOps360 | ${context.pageNumber} / ${context.pagesCount}',
        style: pw.TextStyle(fontSize: 8, color: muted)),
    build: (_) => [
      pw.SizedBox(height: 28, child: brandHeader()),
      pw.SizedBox(height: 14),
      pw.Text(
          settlement.isFinalInvoice
              ? 'MOVE-OUT SETTLEMENT INVOICE'
              : 'TEMPORARY MOVE-OUT SETTLEMENT',
          style: pw.TextStyle(
              fontSize: 18, color: blue, fontWeight: pw.FontWeight.bold)),
      if (!settlement.isFinalInvoice) ...[
        pw.SizedBox(height: 8),
        pw.Container(
          padding: const pw.EdgeInsets.all(10),
          color: PdfColor.fromHex('#FFF3CD'),
          child: pw.Text(
            'Temporary invoice - final utility bills and charges are still pending. A completed invoice will be issued after the final settlement and refund are confirmed.',
            style: pw.TextStyle(fontSize: 9, color: blue),
          ),
        ),
      ],
      pw.SizedBox(height: 18),
      pw.Text(settlement.tenantName),
      pw.Text('${settlement.propertyName} | Unit ${settlement.unitName}'),
      pw.Text('Move-out date: ${settlement.dateLabel}'),
      pw.Text('Refund bank: ${settlement.bankName.isEmpty ? '-' : settlement.bankName}'),
      pw.Text(
          'Refund account: ${settlement.bankAccountNumber.isEmpty ? '-' : settlement.bankAccountNumber}'),
      pw.SizedBox(height: 20),
      pw.Text('Settlement summary',
          style: pw.TextStyle(
              fontSize: 12, color: blue, fontWeight: pw.FontWeight.bold)),
      row('Deposit held', settlementMoney(settlement.deposit), bold: true),
      row('Monthly rent', settlementMoney(settlement.monthlyRent)),
      row('Daily rent (monthly rent / 30)',
          settlementMoney((settlement.monthlyRent / 30).round())),
      pw.Divider(color: line),
      for (final charge in settlement.charges)
        row(charge.$1,
            '${charge.$2 == 0 ? '' : '- '}${settlementMoney(charge.$2)}'),
      pw.Divider(color: line),
      row('Total deductions', settlementMoney(settlement.deductions),
          bold: true),
      pw.SizedBox(height: 12),
      pw.Container(
          width: double.infinity,
          padding: const pw.EdgeInsets.all(16),
          color: green,
          child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Text(
                    settlement.balance >= 0
                        ? (settlement.isRefunded
                            ? 'Amount refunded'
                            : 'Balance to refund')
                        : 'Additional amount due',
                    style: pw.TextStyle(color: refundColor)),
                pw.SizedBox(height: 6),
                pw.Text(settlementMoney(settlement.balance.abs()),
                    style: pw.TextStyle(
                        fontSize: 25,
                        color: refundColor,
                        fontWeight: pw.FontWeight.bold)),
              ])),
      pw.SizedBox(height: 18),
      pw.Text('Refund method: Online bank transfer'),
      pw.SizedBox(height: 8),
      pw.Text(
          'Refund within 3 days after the move-out date, subject to inspection.',
          style: const pw.TextStyle(fontSize: 10)),
      pw.SizedBox(height: 8),
      pw.Text(
          settlement.isRefunded
              ? 'Refunded - confirmed by the owner. Refund payslip attached.'
              : 'This invoice alone is not proof that a refund has been transferred.',
          style: pw.TextStyle(fontSize: 9, color: muted)),
    ],
  ));
  for (final item in <(String, SettlementAttachment?)>[
    ('Payslip', settlement.payslip),
    ('Electricity meter reading', settlement.meter),
  ]) {
    final attachment = item.$2;
    if (attachment == null) continue;
    doc.addPage(pw.Page(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.fromLTRB(50, 24, 50, 26),
        build: (_) => pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.start,
                children: [
                  brandHeader(),
                  pw.SizedBox(height: 34),
                  pw.Text(item.$1,
                      style: pw.TextStyle(fontSize: 19, color: blue)),
                  pw.SizedBox(height: 8),
                  pw.Text(
                      '${settlement.tenantName} | ${settlement.propertyName} | ${settlement.unitName}',
                      style: const pw.TextStyle(fontSize: 10)),
                  pw.SizedBox(height: 6),
                  pw.Text(attachment.name,
                      style: const pw.TextStyle(fontSize: 9)),
                  pw.SizedBox(height: 18),
                  pw.Expanded(
                      child: pw.Center(
                          child: pw.Image(pw.MemoryImage(attachment.bytes),
                              fit: pw.BoxFit.contain))),
                ])));
  }
  return doc.save();
}
